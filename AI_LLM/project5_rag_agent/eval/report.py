"""Gom mọi kết quả đang có trong results/ thành một trang tổng hợp.

Chạy lại bất cứ lúc nào; phần nào chưa chạy thì ghi rõ là CHƯA CÓ thay vì để
trống — người đọc README phải phân biệt được "đo ra 0" với "chưa đo".

    python -m eval.report
"""

from __future__ import annotations

import json

from rag.config import RESULTS_DIR

MISSING = "_not run yet_"


def load(name: str):
    p = RESULTS_DIR / name
    if not p.exists():
        return None
    try:
        return json.loads(p.read_text(encoding="utf-8"))
    except Exception:  # noqa: BLE001
        return None


def pct(v, nd=1):
    return f"{v:.{nd}%}" if isinstance(v, (int, float)) else "—"


def main() -> None:
    L: list[str] = ["# Results summary\n"]
    L.append("Generated by `python -m eval.report`. Every number here traces back to a "
             "JSON file in `results/`; nothing is typed in by hand.\n")

    # ---- 1. retrieval experiments (không cần LLM) -------------------------
    L.append("## 1. Retrieval tuning experiments (deterministic, no LLM)\n")
    exp = load("retrieval_experiments.json")
    if not exp:
        L.append(f"{MISSING} — run `python -m eval.experiments`\n")
    else:
        L.append("| variant | recall | full-recall | precision | MRR | ctx chars |")
        L.append("|---|---|---|---|---|---|")
        for v in exp["variants"]:
            L.append(f"| `{v['name']}` | {pct(v['recall'])} | {pct(v['full_recall'])} "
                     f"| {pct(v['precision'])} | {v['mrr']:.3f} | {v['ctx_chars']:,.0f} |")
        o = exp["out_of_scope"]
        L.append(f"\n**Out-of-scope separability** (`{o['config']}`): lowest in-scope top-1 "
                 f"similarity = `{o['min_in_scope']:.4f}`, highest out-of-scope top-1 = "
                 f"`{o['max_out_of_scope']:.4f}`, gap = `{o['gap']:+.4f}` → "
                 f"**{'separable' if o['separable'] else 'NOT separable'}**.\n")

    # ---- 2. deterministic eval -------------------------------------------
    L.append("## 2. Answer-level evaluation (deterministic metrics)\n")
    tags = [p.stem.replace("eval_", "") for p in sorted(RESULTS_DIR.glob("eval_*.json"))]
    if not tags:
        L.append(f"{MISSING} — run `python -m eval.generate --mode baseline` then "
                 "`python -m eval.run_eval --tags baseline`\n")
    else:
        rows = [("Context recall (labelled)", "context_recall_id", True),
                ("Full-recall rate", "full_recall_rate", True),
                ("Context precision (labelled)", "context_precision_id", True),
                ("Refusal accuracy", "refusal_correct", True),
                ("False-refusal rate", "false_refusal_rate", True),
                ("Citation present", "has_citation", True),
                ("Mean tool calls", "avg_tool_calls", False),
                ("Mean context chars", "avg_ctx_chars", False)]
        data = {t: load(f"eval_{t}.json")["aggregate"] for t in tags}
        L.append("| metric | " + " | ".join(f"`{t}`" for t in tags) + " |")
        L.append("|---|" + "---|" * len(tags))
        # Hàng `n` phải là hàng ĐẦU TIÊN, không phải một chú thích ở dưới.
        # Một cột chạy 2 câu và một cột chạy 20 câu trông y hệt nhau trong bảng này
        # nếu không in mẫu số ra — và người đọc sẽ mặc định là chúng so được với nhau.
        L.append("| **Questions scored (n)** | " + " | ".join(
            str(data[t]["all"].get("n", "—")) for t in tags) + " |")
        for label, key, is_pct in rows:
            cells = []
            for t in tags:
                a = data[t]["all"]
                v = a.get(key)
                cell = pct(v) if is_pct else (f"{v:,.2f}" if isinstance(v, float) else "—")
                cov = a.get("coverage", {}).get(key)
                if cov is not None and cov != a.get("n"):
                    cell += f" ({cov}/{a['n']})"      # mẫu số trong ô, không để bên lề
                cells.append(cell)
            L.append(f"| {label} | " + " | ".join(cells) + " |")
        ns = {t: data[t]["all"].get("n") for t in tags}
        if len({v for v in ns.values() if v is not None}) > 1:
            L.append("")
            L.append("> **These columns are not comparable.** They were scored on different "
                     "numbers of questions (" + ", ".join(f"`{t}` = {v}" for t, v in ns.items())
                     + "). A column scored on a subset is not a result for the whole benchmark; "
                     "run the missing questions before reading this table as a comparison.")
        L.append("")

    # ---- 3. ragas ---------------------------------------------------------
    L.append("## 3. Ragas metrics (LLM-as-judge — treat with caution)\n")
    rtags = [p.stem.replace("ragas_", "") for p in sorted(RESULTS_DIR.glob("ragas_*.json"))]
    if not rtags:
        L.append(f"{MISSING} — run `python -m eval.ragas_eval --tag baseline`\n")
    else:
        data = {t: load(f"ragas_{t}.json") for t in rtags}
        keys = sorted({k for t in rtags for k in data[t]["aggregate"]})
        L.append("| metric | " + " | ".join(f"`{t}`" for t in rtags) + " |")
        L.append("|---|" + "---|" * len(rtags))
        for k in keys:
            L.append(f"| {k} | " + " | ".join(
                str(data[t]["aggregate"].get(k, "—")) for t in rtags) + " |")
        cfgs = {t: data[t].get("metric_config", {}) for t in rtags}
        L.append("")
        L.append("| metric | tag | n scored | judge | context source | refusals dropped |")
        L.append("|---|---|---|---|---|---|")
        for t in rtags:
            for k in sorted(cfgs[t]):
                c = cfgs[t][k]
                L.append(f"| {k} | `{t}` | {c.get('coverage')}/{c.get('n')} | "
                         f"`{c.get('judge_model')}` | {c.get('context_source')} | "
                         f"{'yes' if c.get('drop_refused') else 'no'} |")
        # Cùng một metric nhưng khác mẫu số giữa hai tag = KHÔNG so được.
        # Ví dụ đã gặp: `faithfulness` bỏ câu bị từ chối, mà baseline từ chối `mh02`
        # còn agent thì trả lời -> baseline chấm trên 15 câu, agent trên 16, và câu
        # thứ 16 là câu KHÓ NHẤT. Đặt hai số cạnh nhau là phạt agent vì nó trả lời
        # được nhiều hơn.
        by_metric: dict[str, dict[str, int]] = {}
        for t in rtags:
            for k, c in cfgs[t].items():
                if c.get("n") is not None:
                    by_metric.setdefault(k, {})[t] = c["n"]
        for k, per_tag in by_metric.items():
            if len(set(per_tag.values())) > 1:
                L.append("")
                L.append(f"> **`{k}` is not comparable across these columns.** It was scored on "
                         + ", ".join(f"`{t}` = {v} questions" for t, v in per_tag.items())
                         + ". The column with more questions was graded on a strictly harder "
                           "set, so the raw difference understates it. Compare on the shared "
                           "subset before drawing a conclusion.")
        L.append(f"\nJudge model: `{data[rtags[0]]['judge_model']}`. "
                 "These scores come from an LLM grading another "
                 "LLM's output. They are not measurements in the same sense as section 1 — "
                 "re-running can produce different values. Cross-check individual cases with "
                 "`python -m eval.inspect_run --tag baseline --id mh03`.\n")

    out = RESULTS_DIR / "SUMMARY.md"
    RESULTS_DIR.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"-> {out}")
    print("\n".join(L))


if __name__ == "__main__":
    main()
